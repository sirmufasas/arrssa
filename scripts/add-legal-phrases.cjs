const match = content.match(/export const UNIVERSAL_PHRASES: Record<string, Partial<Record<Language, string>>> = (\{[\s\S]*\});\n$/);
if (!match) {
  console.error("Could not find UNIVERSAL_PHRASES in phrases file!");
  process.exit(1);
}

const existing = eval("(" + match[1] + ")");
const merged = { ...existing, ...LEGAL_PHRASES };

